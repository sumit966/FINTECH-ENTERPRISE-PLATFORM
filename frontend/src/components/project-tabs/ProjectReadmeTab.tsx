import { useMemo, useState } from 'react';
import { Copy, Check, Download, AlertCircle, FileText } from 'lucide-react';
import { Card } from '../ui/Card';
import Button from '../ui/Button';
import Badge from '../ui/Badge';
import type { ProjectDetail } from '../../services/projectService';

interface Props { project: ProjectDetail; }

// ----------------------------------------------------------------------------
// Generates a per-project README from stored project metadata.
// This is prototype documentation — NOT synced with any GitHub repository.
// ----------------------------------------------------------------------------
function generateReadme(p: ProjectDetail): string {
  const techBadges = [
    ...p.techFrontend.map((t) => '![Frontend](https://img.shields.io/badge/Frontend-' + encodeURIComponent(t) + '-3358ff)'),
    ...p.techBackend.map((t) => '![Backend](https://img.shields.io/badge/Backend-' + encodeURIComponent(t) + '-10b981)'),
    ...p.techDatabase.map((t) => '![Database](https://img.shields.io/badge/Database-' + encodeURIComponent(t) + '-f59e0b)'),
    ...p.techCloud.map((t) => '![Cloud](https://img.shields.io/badge/Cloud-' + encodeURIComponent(t) + '-8b5cf6)'),
  ].join(' ');

  return `# ${p.name}

> ${p.projectCode} · ${p.industry} · ${p.country}

${techBadges}

## Overview

**Client**: ${p.client.companyName} (${p.client.country}, ${p.client.industry})
**Status**: ${p.status} · ${p.progressPercent}% complete
**Team size**: ${p.members.length}
**Timeline**: ${new Date(p.startDate).toLocaleDateString('en-IN')} → ${new Date(p.expectedEndDate).toLocaleDateString('en-IN')}

## Business Problem

${p.name} is an enterprise ${p.industry.toLowerCase()} engagement for ${p.client.companyName}. The system is designed to deliver a modern, scalable platform using the following technology stack:

## Technology Stack

### Frontend
${p.techFrontend.length > 0 ? p.techFrontend.map((t) => '- ' + t).join('\n') : '- Not specified'}

### Backend
${p.techBackend.length > 0 ? p.techBackend.map((t) => '- ' + t).join('\n') : '- Not specified'}

### Database
${p.techDatabase.length > 0 ? p.techDatabase.map((t) => '- ' + t).join('\n') : '- Not specified'}

### Cloud & Infrastructure
${p.techCloud.length > 0 ? p.techCloud.map((t) => '- ' + t).join('\n') : '- Not specified'}

${p.techAI.length > 0 ? '### AI / ML\n' + p.techAI.map((t) => '- ' + t).join('\n') + '\n' : ''}

## Architecture

**API Style**: ${p.apiStyle || 'REST'}
**Environment**: ${p.environment}
**Repository**: ${p.repository || 'Not linked'}

### Integrations
${p.integrations.length > 0 ? p.integrations.map((t) => '- ' + t).join('\n') : '- No external integrations listed'}

## Setup Instructions

\`\`\`bash
# Clone the repository
git clone ${p.repository || '<repository-url>'}
cd ${p.name.toLowerCase().replace(/[^a-z0-9]+/g, '-')}

# Install dependencies
npm install

# Configure environment
cp .env.example .env

# Run database migrations
npm run migrate

# Start development server
npm run dev
\`\`\`

## Project Structure

\`\`\`
${p.projectCode.toLowerCase()}/
├── src/
│   ├── components/       # Reusable UI components
│   ├── pages/            # Application screens
│   ├── services/         # API clients
│   ├── utils/            # Helpers
│   └── types/            # TypeScript definitions
├── public/               # Static assets
├── package.json
└── tsconfig.json
\`\`\`

## Environment Variables

\`\`\`env
DATABASE_URL=postgresql://...
API_BASE_URL=https://api.example.in
JWT_SECRET=<generated-secret>
CORS_ORIGIN=https://app.example.in
\`\`\`

## Team

${p.projectManager ? '**Project Manager**: ' + p.projectManager.fullName + ' (`' + p.projectManager.employeeCode + '`)' : ''}

### Assigned Engineers
${p.members.length > 0 ? p.members.map((m) => '- **' + m.fullName + '** (`' + m.employeeCode + '`) — ' + m.role + ' @ ' + m.allocation + '%').join('\n') : '- No members assigned'}

## Status

- **Health**: ${p.healthScore != null ? p.healthScore.toFixed(2) + '/5.00' : 'Not scored'}
- **Risk**: ${p.riskScore != null ? p.riskScore.toFixed(2) + '/5.00' : 'Not scored'}
- **Security**: ${p.securityStatus}
- **QA**: ${p.qaStatus}

## Changelog

- Initial project kickoff: ${new Date(p.startDate).toLocaleDateString('en-IN')}
- Latest update: ${new Date().toLocaleDateString('en-IN')}

---

*This README was auto-generated by the Nexus Enterprise Platform from project metadata. It is prototype documentation and is not synced with any external repository.*
`;
}

export default function ProjectReadmeTab({ project }: Props) {
  const readme = useMemo(() => generateReadme(project), [project]);
  const [copied, setCopied] = useState(false);
  const [ReactMarkdown, setReactMarkdown] = useState<any>(null);
  const [remarkGfm, setRemarkGfm] = useState<any>(null);
  const [loadFailed, setLoadFailed] = useState(false);

  // Try to dynamically load react-markdown for rich rendering.
  // Falls back to <pre> if not installed.
  useState(() => {
    (async () => {
      try {
        const md = await import('react-markdown');
        const gfm = await import('remark-gfm');
        setReactMarkdown(() => md.default);
        setRemarkGfm(() => gfm.default);
      } catch {
        setLoadFailed(true);
      }
    })();
  });

  const copyReadme = async () => {
    try {
      await navigator.clipboard.writeText(readme);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch { /* ignore */ }
  };

  const downloadReadme = () => {
    const blob = new Blob([readme], { type: 'text/markdown;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = project.projectCode + '-README.md';
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  return (
    <div className="space-y-5">
      <Card className="border-amber-500/30 bg-amber-500/5 card-hover">
        <div className="flex items-start gap-2 text-xs text-amber-700 dark:text-amber-300">
          <AlertCircle size={14} className="mt-0.5 shrink-0" />
          <div>
            <strong>Prototype documentation.</strong> This README is auto-generated from the project's stored metadata.
            It is not synchronized with any external repository. Setup commands are illustrative patterns, not verified for this specific project.
          </div>
        </div>
      </Card>

      <Card className="card-hover" padded={false}>
        <div className="flex items-center justify-between gap-3 px-5 py-4 border-b border-slate-200 dark:border-slate-800">
          <div className="flex items-center gap-2">
            <FileText size={16} className="text-brand-500" />
            <div className="font-medium text-sm">README.md</div>
            <Badge tone="brand">{project.projectCode}</Badge>
          </div>
          <div className="flex items-center gap-2">
            <Button variant="ghost" size="sm" onClick={copyReadme}>
              {copied ? <Check size={14} /> : <Copy size={14} />}
              {copied ? 'Copied' : 'Copy'}
            </Button>
            <Button variant="secondary" size="sm" onClick={downloadReadme}>
              <Download size={14} /> Download .md
            </Button>
          </div>
        </div>

        <div className="p-6">
          {!ReactMarkdown || loadFailed ? (
            <pre className="text-xs whitespace-pre-wrap font-mono bg-slate-50 dark:bg-slate-900/60 rounded-md p-4 overflow-x-auto">
              {readme}
            </pre>
          ) : (
            <div className="prose prose-slate dark:prose-invert max-w-none
              prose-headings:tracking-tight prose-headings:font-semibold
              prose-h1:text-2xl prose-h1:mb-3
              prose-h2:text-lg prose-h2:mt-6 prose-h2:mb-2 prose-h2:border-b prose-h2:border-slate-200 dark:prose-h2:border-slate-800 prose-h2:pb-1
              prose-h3:text-base prose-h3:mt-4
              prose-p:text-sm prose-p:leading-relaxed
              prose-a:text-brand-500 prose-a:no-underline hover:prose-a:underline
              prose-code:text-xs prose-code:bg-slate-100 dark:prose-code:bg-slate-800 prose-code:px-1 prose-code:py-0.5 prose-code:rounded
              prose-pre:bg-slate-900 prose-pre:text-slate-100 prose-pre:text-xs prose-pre:rounded-lg prose-pre:p-4 prose-pre:overflow-x-auto
              prose-ul:text-sm prose-li:my-0.5
              prose-table:text-sm
              prose-blockquote:border-l-brand-500 prose-blockquote:text-slate-500">
              <ReactMarkdown remarkPlugins={remarkGfm ? [remarkGfm] : []}>
                {readme}
              </ReactMarkdown>
            </div>
          )}
        </div>
      </Card>
    </div>
  );
}